function main() {
  const langs = fs.readdirSync(LOCALES_DIR)
    .filter(name => fs.statSync(path.join(LOCALES_DIR, name)).isDirectory());

  for (const lang of langs) {
    const file = path.join(LOCALES_DIR, lang, 'translation.json');
    const json = JSON.parse(fs.readFileSync(file, 'utf8'));

    const t = T[lang] || T.en;
    let added = 0;

    if (!json.order) json.order = {};
    for (const key of Object.keys(ORDER_KEYS)) {
      if (json.order[key] === undefined && t[key] !== undefined) {
        json.order[key] = t[key];
        added++;
      }
    }

    if (!json.products) json.products = {};
    for (const key of Object.keys(PRODUCT_KEYS)) {
      if (json.products[key] === undefined && t[key] !== undefined) {
        json.products[key] = t[key];
        added++;
      }
    }

    fs.writeFileSync(file, JSON.stringify(json, null, 4) + '\n', 'utf8');
    console.log(`${lang}: +${added} keys`);
  }
}

main();
